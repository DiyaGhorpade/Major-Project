"""Transparent rule-based recommendations. HEURISTIC suggestions only - not an expert diagnosis.

Design rules (see docs/MODEL_CARD.md):
* a flagged sensor anomaly -> only "verify the sensor" (no plant-stress inference from a suspect sample);
* missing inputs or low model confidence -> "take another reading", no strong recommendation;
* condition-based suggestions need most of the last few readings (or their rolling mean) to agree (never a single sample);
* no watering volumes or rigid biological thresholds; monitoring ranges come from config.yaml.
"""
from __future__ import annotations

import math

import pandas as pd

from .config import Config
from .schema import SENSOR_COLUMNS

DISCLAIMER = "Suggestions are generated by simple rules from sensor readings and model outputs."
_PRIORITY_BY_LABEL = {"healthy": "low", "low": "low", "moderate": "medium", "high": "high"}


def _rec(rec_id: str, category: str, text: str, reason: str, priority: str, features: dict) -> dict:
    return {"id": rec_id, "category": category, "text": text, "reason": reason, "priority": priority,
            "supporting_features": {k: (None if (isinstance(v, float) and math.isnan(v)) else v) for k, v in features.items()},
            "type": "heuristic_suggestion"}


def _rolling_mean(recent: pd.DataFrame, col: str):
    """The causal ``<col>_roll6_mean`` feature of the latest row; falls back to the mean of the trailing rows."""
    v = _num(recent.iloc[-1].get(f"{col}_roll6_mean"))
    if v is None and len(recent) >= 3:
        v = _num(recent[col].tail(6).mean())
    return v


def _num(v):
    return None if v is None or (isinstance(v, float) and math.isnan(v)) else float(v)


def generate_recommendations(label: str, probabilities: dict, is_anomaly: bool, missing_inputs: list[str],
                             recent: pd.DataFrame, cfg: Config) -> list[dict]:
    """``recent`` = trailing feature rows for THIS plant (oldest -> newest, last row is the one predicted)."""
    r = cfg.get("recommendations", {}) or {}
    n_consistent = int(r.get("min_consistent_rows", 3))
    latest = recent.iloc[-1]
    max_prob = max(probabilities.values()) if probabilities else 0.0
    base_priority = _PRIORITY_BY_LABEL.get(label, "low")

    if is_anomaly:
        return [_rec("verify_sensor", "data_quality",
                     "This reading looks unusual for this plant's recent history. Check the sensor, wiring and node "
                     "connection and take another reading before drawing conclusions about plant stress.",
                     "Isolation-forest anomaly flag on the latest reading; a single anomalous sample can be a sensor or "
                     "data-quality problem rather than a plant problem.",
                     "medium", {c: _num(latest.get(c)) for c in SENSOR_COLUMNS})]
    if missing_inputs:
        return [_rec("retake_reading", "data_quality",
                     f"Sensor value(s) missing ({', '.join(missing_inputs)}). Take another reading before acting on this result.",
                     "Required inputs were missing in the latest reading, so the prediction is less reliable.",
                     "low", {"missing": missing_inputs})]
    if max_prob < float(r.get("low_confidence_max_prob", 0.45)):
        return [_rec("low_confidence", "model_confidence",
                     "The model is not confident about this reading. Take another reading and compare with the next few.",
                     f"Highest class probability is {max_prob:.2f}, below the configured confidence floor "
                     f"({r.get('low_confidence_max_prob', 0.45)}).",
                     "low", {"max_probability": round(max_prob, 3)})]

    tail = recent.tail(n_consistent)
    enough = len(tail) >= n_consistent
    recs: list[dict] = []

    def all_true(mask) -> bool:
        return bool(enough and len(mask) == n_consistent and mask.notna().all() and mask.all())

    # --- soil moisture -------------------------------------------------------------
    soil_low = float(r.get("soil_low_pct", 25))
    if enough and all_true(tail["soil"].notna() & (tail["soil"] < soil_low)):
        recs.append(_rec("check_watering", "soil",
                         "Soil moisture has stayed low for several readings. Check the soil moisture and your watering schedule.",
                         f"Last {n_consistent} soil readings are below the configured monitoring level ({soil_low}%).",
                         base_priority, {"soil_last": _num(latest["soil"]), "soil_roll6_mean": _num(latest.get("soil_roll6_mean"))}))
    else:
        fast = float(r.get("soil_fast_drop_pct_per_hr", -1.5))
        rate = tail["soil_rate_per_hr"] if enough else None
        if enough and rate.notna().all() and rate.mean() < fast:
            recs.append(_rec("check_soil_drying", "soil",
                             "Soil moisture is dropping quickly. Check the soil moisture and watering schedule soon.",
                             f"Mean soil change over the last {n_consistent} readings is {rate.mean():.2f} %/h "
                             f"(configured fast-drop level {fast} %/h).",
                             base_priority, {"soil_rate_per_hr_mean": float(rate.mean()), "soil_last": _num(latest["soil"])}))

    # --- light (daytime only) ---------------------------------------------------
    d0, d1 = (int(x) for x in r.get("daytime_hours", [9, 16]))
    day_rows = recent.tail(max(n_consistent * 2, 6))
    day_rows = day_rows[(day_rows["hour"] >= d0) & (day_rows["hour"] <= d1)].tail(n_consistent)
    if len(day_rows) >= n_consistent and day_rows["light"].notna().all():
        if (day_rows["light"] < float(r.get("light_low_lux", 300))).all():
            recs.append(_rec("check_light_low", "light",
                             "Daytime light has been very low over several readings. Check the plant's placement and access to indirect light.",
                             f"Last {n_consistent} daytime readings are below {r.get('light_low_lux', 300)} lux.",
                             base_priority, {"light_last": _num(latest["light"]), "daytime_light_mean": float(day_rows["light"].mean())}))
        elif (day_rows["light"] > float(r.get("light_high_lux", 20000))).all():
            recs.append(_rec("check_light_high", "light",
                             "Daytime light has been unusually high over several readings. Check whether the plant is exposed to direct sun.",
                             f"Last {n_consistent} daytime readings are above {r.get('light_high_lux', 20000)} lux.",
                             base_priority, {"light_last": _num(latest["light"]), "daytime_light_mean": float(day_rows["light"].mean())}))

    # --- temperature / humidity / VPD ---------------------------------------------
    # Two ways to flag climate: (1) enough of the last few readings are individually out of range, or
    # (2) the 6-reading rolling mean (a causal feature) sits outside a sustained-deviation band, which catches
    # a pot that stays cool/warm/damp/dry without every single reading crossing the hard limits.
    if enough:
        t_hi, t_lo = float(r.get("temp_high_c", 32)), float(r.get("temp_low_c", 18))
        h_lo, h_hi = float(r.get("humidity_low_pct", 40)), float(r.get("humidity_high_pct", 85))
        v_hi = float(r.get("vpd_high_kpa", 2.0))
        n_hits = max(1, min(n_consistent, int(r.get("climate_min_hits", 2))))
        reasons = []

        def often(mask) -> bool:
            """At least ``n_hits`` of the trailing window are out of range (NaN counts as not out of range)."""
            return bool(len(mask) == n_consistent and int(mask.fillna(False).sum()) >= n_hits)

        some = f"at least {n_hits} of the last {n_consistent} readings"
        if often(tail["temperature"] > t_hi):
            reasons.append(f"temperature above {t_hi} C in {some}")
        if often(tail["temperature"] < t_lo):
            reasons.append(f"temperature below {t_lo} C in {some}")
        if often(tail["humidity"] < h_lo):
            reasons.append(f"humidity below {h_lo}% in {some}")
        if often(tail["humidity"] > h_hi):
            reasons.append(f"humidity above {h_hi}% in {some}")
        if often(tail["vpd"] > v_hi):
            reasons.append(f"air VPD above {v_hi} kPa in {some}")

        t_mean, h_mean = _rolling_mean(recent, "temperature"), _rolling_mean(recent, "humidity")
        band = {k: float(r[k]) for k in ("temp_mean_high_c", "temp_mean_low_c", "humidity_mean_low_pct", "humidity_mean_high_pct") if k in r}
        if t_mean is not None and t_mean > band.get("temp_mean_high_c", math.inf):
            reasons.append(f"recent mean temperature {t_mean:.1f} C is above {band['temp_mean_high_c']} C")
        if t_mean is not None and t_mean < band.get("temp_mean_low_c", -math.inf):
            reasons.append(f"recent mean temperature {t_mean:.1f} C is below {band['temp_mean_low_c']} C")
        if h_mean is not None and h_mean < band.get("humidity_mean_low_pct", -math.inf):
            reasons.append(f"recent mean humidity {h_mean:.0f}% is below {band['humidity_mean_low_pct']}%")
        if h_mean is not None and h_mean > band.get("humidity_mean_high_pct", math.inf):
            reasons.append(f"recent mean humidity {h_mean:.0f}% is above {band['humidity_mean_high_pct']}%")
        if reasons:
            damp = any("humidity" in x and "above" in x for x in reasons)
            recs.append(_rec("check_climate", "temperature_humidity",
                             "Temperature / humidity conditions have stayed outside the monitoring range. Check temperature, airflow and humidity around the plant"
                             + (" (improve ventilation / reduce humidity if the air is damp)." if damp else "."),
                             "Recent readings: " + "; ".join(reasons) + ". (Air VPD is approximate, not leaf-level.)",
                             base_priority, {"temperature_last": _num(latest["temperature"]), "humidity_last": _num(latest["humidity"]),
                                             "vpd_last": _num(latest["vpd"]), "temperature_roll6_mean": t_mean, "humidity_roll6_mean": h_mean}))

    if not recs and label in ("moderate", "high"):
        recs.append(_rec("monitor_and_inspect", "general",
                         "The model rates this plant's recent readings as stressed, but no single sensor condition explains it. "
                         "Keep monitoring and inspect the plant and sensors in person.",
                         f"Predicted class is '{label}' without a persistent out-of-range sensor condition under the configured ranges.",
                         base_priority, {"predicted_label": label}))
    elif not recs and label == "low":
        recs.append(_rec("monitor_and_inspect", "general",
                         "The model sees early or mild signs of stress in this plant's recent readings, but no single sensor condition explains it. "
                         "Keep an eye on the next few readings and give the plant and sensors a quick check.",
                         "Predicted class is 'low' without a persistent out-of-range sensor condition under the configured ranges.",
                         base_priority, {"predicted_label": label}))
    return recs
