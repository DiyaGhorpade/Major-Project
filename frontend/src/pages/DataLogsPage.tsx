import React, { useEffect, useState } from 'react';
import {
  Download,
  Search,
  ChevronLeft,
  ChevronRight,
} from 'lucide-react';
import { apiClient, type ReadingFilter } from '../api/client';
import { SensorRecord } from '../types';
import { useDataLogs } from '../hooks/useReadings';
import { usePlants } from '../hooks/usePlants';
import { useSessions } from '../hooks/useData';
import { ErrorState } from '../components/shared/ErrorState';
import { StatusBadge } from '../components/shared/StatusBadge';
import { RecordDetailDrawer } from '../components/shared/RecordDetailDrawer';
import { clearSessionFilter, peekSessionFilter } from '../components/monitoring/format';
import { formatPercent, formatTemp, formatLux, formatCount, formatDateTime, orNA } from '../lib/utils';

export const DataLogsPage: React.FC = () => {
  const [selectedRecord, setSelectedRecord] = useState<SensorRecord | null>(null);

  // Filters
  const [searchQuery, setSearchQuery] = useState('');
  const [plantFilter, setPlantFilter] = useState('all');
  const [nodeFilter, setNodeFilter] = useState('all');
  const [statusFilter, setStatusFilter] = useState('all');
  // A session picked on the Sessions page is handed over through sessionStorage. Reading it is pure (safe when React
  // double-invokes initializers under StrictMode); it is consumed in an effect once the page has taken it.
  const [sessionFilter, setSessionFilter] = useState<string>(() => {
    const id = peekSessionFilter();
    return id === null ? 'all' : String(id);
  });
  useEffect(() => {
    clearSessionFilter();
  }, []);

  // Pagination
  const [currentPage, setCurrentPage] = useState(1);
  const [pageSize, setPageSize] = useState(15);

  // Server-side filtering, search and pagination (the backend returns the page and X-Total-Count).
  const filter: ReadingFilter = {
    plantId: plantFilter,
    nodeId: nodeFilter,
    status: statusFilter,
    sessionId: sessionFilter === 'all' ? undefined : Number(sessionFilter),
    q: searchQuery.trim() || undefined,
    limit: pageSize,
    offset: (currentPage - 1) * pageSize,
  };
  const logs = useDataLogs(filter);
  const plantsQuery = usePlants();
  const sessionsQuery = useSessions();
  const plants = plantsQuery.data ?? [];
  const sessions = sessionsQuery.data ?? [];
  const paginatedRecords: SensorRecord[] = logs.data ?? [];
  const totalRecords = logs.total;
  const totalPages = Math.max(1, Math.ceil(totalRecords / pageSize));
  const startIndex = (currentPage - 1) * pageSize;
  // The CSV is generated by the server for the same filters (all matching rows, not just this page).
  const csvUrl = apiClient.dataLogsCsvUrl(filter);

  return (
    <div className="space-y-6">
      {/* Top Header & Export Action */}
      <div className="bg-white rounded-card border border-[#DCE4D9] p-5 shadow-card flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <span className="text-xs font-bold uppercase tracking-wider text-[#426B4F]">
              Raw Telemetry Repository
            </span>
            <span className="text-xs px-2.5 py-0.5 rounded-full bg-[#EDF4EB] text-[#2E8B57] font-semibold border border-[#DDE8D8]">
              {formatCount(totalRecords)} {totalRecords === 1 ? 'Record' : 'Records'} Match
            </span>
          </div>
          <h1 className="text-lg font-bold text-[#1C2B23]">
            Historical Sensor Telemetry Database
          </h1>
          <p className="text-xs text-[#6B786E] mt-1">
            Stored sensor records from the bundled dataset. Click any row for the full record, model output and dataset labels.
          </p>
        </div>

        <a
          href={csvUrl}
          download
          className="px-4 py-2 bg-[#2E8B57] hover:bg-[#236e44] text-white text-xs font-bold rounded-lg flex items-center gap-2 transition-all shadow-sm"
        >
          <Download className="w-4 h-4" />
          <span>Download Filtered CSV ({formatCount(totalRecords)})</span>
        </a>
      </div>

      {/* Filter Toolbar */}
      <div className="bg-white rounded-card border border-[#DCE4D9] p-4 shadow-card flex flex-wrap items-center justify-between gap-3">
        <div className="flex flex-wrap items-center gap-3 flex-1">
          {/* Search */}
          <div className="relative min-w-[220px] flex-1 max-w-xs">
            <Search className="w-4 h-4 text-stone-400 absolute left-3 top-1/2 -translate-y-1/2" />
            <input
              type="text"
              placeholder="Search by pot, session, node, record id or date..."
              value={searchQuery}
              onChange={(e) => {
                setSearchQuery(e.target.value);
                setCurrentPage(1);
              }}
              className="w-full text-xs bg-[#F6F7F0] border border-[#DCE4D9] rounded-lg pl-9 pr-3 py-1.5 outline-none focus:border-[#2E8B57] focus:bg-white text-[#1C2B23]"
            />
          </div>

          {/* Plant filter */}
          <select
            aria-label="Pot filter"
            value={plantFilter}
            onChange={(e) => {
              setPlantFilter(e.target.value);
              setCurrentPage(1);
            }}
            className="text-xs bg-white border border-[#DCE4D9] rounded-lg px-3 py-1.5 text-[#1C2B23] outline-none shadow-sm cursor-pointer"
          >
            <option value="all">All Pots ({plants.length || 'n/a'})</option>
            {plants.map((p) => (
              <option key={p.id} value={p.id}>
                Pot #{p.id} ({p.variety})
              </option>
            ))}
          </select>

          {/* Node filter */}
          <select
            aria-label="Node filter"
            value={nodeFilter}
            onChange={(e) => {
              setNodeFilter(e.target.value);
              setCurrentPage(1);
            }}
            className="text-xs bg-white border border-[#DCE4D9] rounded-lg px-3 py-1.5 text-[#1C2B23] outline-none shadow-sm cursor-pointer"
          >
            <option value="all">All Nodes</option>
            <option value="1">Node 1</option>
            <option value="2">Node 2</option>
          </select>

          {/* Status filter */}
          <select
            aria-label="Status filter"
            value={statusFilter}
            onChange={(e) => {
              setStatusFilter(e.target.value);
              setCurrentPage(1);
            }}
            className="text-xs bg-white border border-[#DCE4D9] rounded-lg px-3 py-1.5 text-[#1C2B23] outline-none shadow-sm cursor-pointer"
          >
            <option value="all">All Statuses</option>
            <option value="accepted">Accepted</option>
            <option value="flagged">Flagged (missing or out-of-range values)</option>
            <option value="rejected">Rejected</option>
          </select>

          {/* Session filter */}
          <select
            aria-label="Session filter"
            value={sessionFilter}
            onChange={(e) => {
              setSessionFilter(e.target.value);
              setCurrentPage(1);
            }}
            className="text-xs bg-white border border-[#DCE4D9] rounded-lg px-3 py-1.5 text-[#1C2B23] outline-none shadow-sm cursor-pointer"
          >
            <option value="all">All Sessions</option>
            {sessions.map((sess) => (
              <option key={sess.session_id} value={sess.session_id}>
                Session #{sess.session_id}
              </option>
            ))}
          </select>
        </div>

        {/* Page size selector */}
        <div className="flex items-center gap-2 text-xs text-[#6B786E]">
          <span>Per page:</span>
          <select
            value={pageSize}
            onChange={(e) => {
              setPageSize(Number(e.target.value));
              setCurrentPage(1);
            }}
            className="bg-[#EDF4EB] border border-[#DDE8D8] rounded px-2 py-1 font-semibold text-[#173F32] outline-none cursor-pointer"
          >
            <option value={10}>10</option>
            <option value={15}>15</option>
            <option value={25}>25</option>
            <option value={50}>50</option>
          </select>
        </div>
      </div>

      {logs.error && <ErrorState message={logs.error.message} onRetry={() => void logs.refetch()} />}

      {/* Main Records Table — Exact Specified Schema Headers */}
      <div className="bg-white rounded-card border border-[#DCE4D9] shadow-card overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-xs text-left">
            <thead>
              <tr className="border-b border-[#DCE4D9] text-[#6B786E] bg-[#F6F7F0]/60">
                <th className="py-3 px-4 font-semibold">timestamp (IST)</th>
                <th className="py-3 px-4 font-semibold">session_id</th>
                <th className="py-3 px-4 font-semibold">node_id</th>
                <th className="py-3 px-4 font-semibold">sampling_point</th>
                <th className="py-3 px-4 font-semibold">plant_id</th>
                <th className="py-3 px-4 font-semibold">soil (%)</th>
                <th className="py-3 px-4 font-semibold">temperature (°C)</th>
                <th className="py-3 px-4 font-semibold">humidity (%)</th>
                <th className="py-3 px-4 font-semibold">light (lux)</th>
                <th className="py-3 px-4 font-semibold">status</th>
                <th className="py-3 px-4 font-semibold">validation_error</th>
                <th className="py-3 px-4 font-semibold text-right">Inspect</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-[#DCE4D9]/60 font-mono">
              {paginatedRecords.length === 0 && (
                <tr>
                  <td colSpan={12} className="py-8 px-4 text-center text-stone-500 font-sans">
                    {logs.loading ? 'Loading records...' : 'No records match these filters.'}
                  </td>
                </tr>
              )}
              {paginatedRecords.map((r) => (
                <tr
                  key={r.record_id}
                  onClick={() => setSelectedRecord(r)}
                  className="hover:bg-[#EDF4EB]/40 transition-colors cursor-pointer"
                >
                  <td className="py-3 px-4 text-[#1C2B23] font-medium" title={r.timestamp}>
                    {formatDateTime(r.timestamp)}
                  </td>
                  <td className="py-3 px-4 text-stone-700">
                    {orNA(r.session_id)}
                  </td>
                  <td className="py-3 px-4 font-bold text-stone-800">
                    {r.node_id}
                  </td>
                  <td className="py-3 px-4 text-stone-700">
                    {orNA(r.sampling_point)}
                  </td>
                  <td className="py-3 px-4 font-bold text-[#102F26]">
                    Pot #{r.plant_id}
                  </td>
                  <td className="py-3 px-4 font-bold text-[#2E8B57]">
                    {formatPercent(r.soil)}
                  </td>
                  <td className="py-3 px-4 text-[#1C2B23] font-semibold">
                    {formatTemp(r.temperature)}
                  </td>
                  <td className="py-3 px-4 text-[#1C2B23]">
                    {formatPercent(r.humidity)}
                  </td>
                  <td className="py-3 px-4 text-[#1C2B23]">
                    {formatLux(r.light)}
                  </td>
                  <td className="py-3 px-4 font-sans">
                    <StatusBadge status={r.status} size="sm" />
                  </td>
                  <td className="py-3 px-4 text-amber-800" data-testid="validation-cell">
                    {orNA(r.validation_error)}
                  </td>
                  <td className="py-3 px-4 text-right">
                    <button
                      onClick={(e) => {
                        e.stopPropagation();
                        setSelectedRecord(r);
                      }}
                      className="px-2.5 py-1 text-xs rounded bg-[#EDF4EB] text-[#2E8B57] font-semibold hover:bg-[#DDE8D8] transition-colors"
                    >
                      Details
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        {/* Pagination Footer */}
        <div className="p-4 border-t border-[#DCE4D9] bg-[#F6F7F0]/40 flex flex-wrap items-center justify-between gap-3 text-xs text-[#6B786E]">
          <div>
            Showing <span className="font-semibold text-[#1C2B23]">{totalRecords === 0 ? 0 : startIndex + 1}</span> to{' '}
            <span className="font-semibold text-[#1C2B23]">
              {Math.min(startIndex + pageSize, totalRecords)}
            </span>{' '}
            of <span className="font-semibold text-[#1C2B23]">{totalRecords}</span> records
          </div>

          <div className="flex items-center gap-1.5">
            <button
              onClick={() => setCurrentPage((p) => Math.max(1, p - 1))}
              disabled={currentPage === 1}
              className="p-1.5 rounded-md border border-[#DCE4D9] bg-white text-[#1C2B23] disabled:opacity-40 hover:bg-[#EDF4EB] transition-colors"
            >
              <ChevronLeft className="w-4 h-4" />
            </button>

            <span className="px-3 font-semibold text-[#1C2B23]">
              Page {currentPage} of {totalPages}
            </span>

            <button
              onClick={() => setCurrentPage((p) => Math.min(totalPages, p + 1))}
              disabled={currentPage === totalPages}
              className="p-1.5 rounded-md border border-[#DCE4D9] bg-white text-[#1C2B23] disabled:opacity-40 hover:bg-[#EDF4EB] transition-colors"
            >
              <ChevronRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      </div>

      <RecordDetailDrawer
        record={selectedRecord}
        onClose={() => setSelectedRecord(null)}
      />
    </div>
  );
};
